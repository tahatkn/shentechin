export function t(lang, key) {
  const v = UI[lang] && UI[lang][key];
  if (v === undefined) {
    const fallback = UI.en[key];
    if (fallback === undefined) throw new Error(`Eksik çeviri anahtarı: ${key}`);
    return fallback;
  }
  return v;
}

